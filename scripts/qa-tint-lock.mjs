// qa-tint-lock — HARDENS the iOS CHROME-TINT system in public/checkit.html. This is a LOCK: if an edit
// breaks any invariant below, the ship FAILS before it reaches the site.
//
// WHY THIS FILE EXISTS (owner order, 2026-07-27): the tint took an all-day on-device hunt to get right,
// and it has been broken more than once by well-meaning edits. Code comments were NOT enough. Nothing
// here is cosmetic preference — every line encodes a behaviour of iOS Safari that you cannot see in a
// headless browser, so a change that "looks fine" locally can still wreck the owner's phone.
//
// ── THE ONE THING TO UNDERSTAND BEFORE YOU TOUCH ANY OF THIS ──
// iOS Safari paints BOTH pieces of its furniture (the status-bar strip AND the bottom bar) using the
// page's ONE declared ROOT background-COLOR. It does not sample painted pixels (that's macOS), and it
// ignores theme-color. You get ONE colour for BOTH edges — there is no way to split them.
//
// Everything follows from that:
//   * The root stays the neutral base dark, so BOTH edges blend invisibly (apple.com-style).
//   * The verdict colour therefore cannot touch either edge. It BLOOMS in the MIDDLE instead:
//     neutral at 0px -> tone by 110px -> tone to 230px -> neutral again by one viewport.
//     That is the "middle bloom". Stretching the tone to the top or bottom WILL tint the chrome.
//   * Nothing may recolour the root in-page in v2: iOS re-reads it at unpredictable moments, so an
//     in-page change produces a random-looking flash on a real device.
//   * The page's bottom must land on the SAME colour as the root, or you get a visible seam right
//     above the bottom bar (this is exactly the 07-27 bug: a parked off-screen sheet was casting an
//     upward shadow onto the last ~40px of the page, so the page went dark and the bar stayed light).
//
// If you believe an invariant here is wrong, do NOT edit this file to make your change pass. Take it to
// the owner. This gate is the only thing standing between the tint and another lost day.
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
const here = dirname(fileURLToPath(import.meta.url));
const html = readFileSync(join(here, "../public/checkit.html"), "utf8");
const admin = readFileSync(join(here, "../public/app.html"), "utf8");
let pass = 0, fail = 0;
const ok = (m) => { pass++; console.log(`  ✓ ${m}`); };
const no = (m) => { fail++; console.log(`  ✗ ${m}`); };
const has = (re, m) => (re.test(html) ? ok(m) : no(m));
const absent = (re, m) => (re.test(html) ? no(m) : ok(m));
const aHas = (re, m) => (re.test(admin) ? ok(m) : no(m));
const aAbsent = (re, m) => (re.test(admin) ? no(m) : ok(m));

console.log("\n▭▭▭ iOS chrome-tint LOCK ▭▭▭");

// ── A. The root colour: the single colour iOS paints both chrome edges with ──
// 1. v2's root colour is the neutral base dark. Change this and BOTH Safari edges change with it.
has(/html\[data-skin="v2"\]\s*\{\s*background:\s*#1D1D22/i,
  "v2 root background is #1D1D22 (the colour iOS paints BOTH chrome edges)");
// 2. The page floor (--bg) must equal the root colour, or the page bottom seams against the bottom bar.
has(/html\[data-skin="v2"\][^}]*--bg:\s*#1D1D22/i,
  "v2 --bg matches the root exactly (page floor == chrome, no seam)");
// 3. In v2 the root is NEVER recoloured in-page — the sheet-open recolour stays scoped to the base skin.
has(/html:not\(\[data-skin="v2"\]\):has\(#acctOverlay\.on\)/,
  "sheet-open root recolour stays scoped to :not(v2) — v2 root never changes in-page");

// ── B. The middle bloom: tone lives in the MIDDLE, never at either edge ──
const bloom = (tone, name) =>
  has(new RegExp(`var\\(--bg\\)\\s*0px,\\s*${tone}\\s*110px,\\s*${tone}\\s*230px,\\s*var\\(--bg\\)\\s*100dvh`, "i"),
    `${name} wash keeps the middle-bloom shape (neutral 0 -> tone 110/230 -> neutral by 100dvh)`);
bloom("#266440", "in-stock");
bloom("#6b2427", "out-of-stock");
bloom("#6c5419", "unclear");
bloom("#6e490f", "restock-soon");
// 8. A page with no verdict is ONE flat colour top to bottom — no gradient to mismatch the chrome.
has(/body:not\(\.rview\)\s*\{\s*background:\s*var\(--bg\)\s*\}/,
  "neutral (no-verdict) page is one solid var(--bg), never a gradient");
// 9. Installed PWA has no Apple furniture, so it KEEPS the full to-the-top tint. Don't delete this block.
has(/@media\s*\(display-mode:\s*standalone\)[\s\S]{0,400}background-color:\s*#266440/i,
  "standalone (installed) keeps its full-tint block — only browser Safari gets the middle bloom");

// ── C. theme-color is a trap: ONE meta tints BOTH edges ──
absent(/<meta[^>]+name=["']theme-color["']/i,
  "no theme-color meta (one meta would tint both edges the same and break the bloom)");
has(/function\s+setThemeTone\s*\(\s*\)\s*\{\s*\}/,
  "setThemeTone stays a deliberate no-op (tone comes from iOS page sampling, not a meta)");

// ── D. The bottom edge: the page must meet the bar on the same colour ──
// 12/13. A PARKED sheet must cast no shadow. Its upward shadow bled onto the page's last ~40px and
// darkened it, so the bar read lighter than the page (the 07-27 seam). Both skins need the rule
// because the v2 selector outranks the base one.
has(/\.csheet:not\(\.on\)\s*\{\s*box-shadow:\s*none\s*\}/,
  "parked call sheet casts NO shadow (base skin) — no dark band above the bottom bar");
has(/html\[data-skin="v2"\]\s*\.csheet:not\(\.on\)\s*\{\s*box-shadow:\s*none\s*\}/,
  "parked call sheet casts NO shadow (v2 skin, outranks the base rule)");
// 14. The footer must stay transparent. Any fill there paints a band that the bottom bar won't match.
has(/html\[data-skin="v2"\]\s*\.site-footer\s*\{\s*background:\s*transparent/,
  "footer stays transparent (a fill would band the page bottom against the bar)");
// 14b. NEVER pad the check status page out to force a scroll (tried 07-30, reverted same day). The
// live view follows the conversation by scrolling to the page bottom as each line lands, so dead space
// under the log strands the newest line off-screen and kills the scroll-back reveal at the end. The
// solid bottom bar on this page is still open; it does NOT get fixed with page height.
absent(/body\.lview\s+main\s*\{[^}]*min-height/,
  "check status page is never padded to a forced height (it would break the follow-along scroll)");

// ── E. Chrome must not change while you scroll ──
// 15. The bottom stays "as boring as possible" (owner). No scroll handler may repaint the chrome.
absent(/addEventListener\(\s*['"]scroll['"][^)]*\)[^;]{0,200}(theme-color|documentElement\.style\.background)/i,
  "no scroll-triggered chrome repaint (the bottom stays boring)");

// ══════════════════════════════════════════════════════════════════════════════════════════════
// THE ADMIN (public/app.html) — same iOS behaviour, same lock (owner order 2026-07-30:
// "make sure the tint is locked and it can never go back to that darker colour border on the
// bottom where the Safari url is"). The Admin wears the WEBSITE's proven recipe: one root
// colour for both bar strips, the page floor on that same colour, nothing repainting it.
// Three separate bugs produced that darker bottom band, and each one is pinned below:
//   * the root colour drifting away from the page floor → a seam right above the bar;
//   * a fixed, filled element parked on the bottom edge (the closed sheet) → the bar sat in
//     the UI layer iOS never re-samples and went flat grey until a reload;
//   * the sheet nudge re-stamping the root background-colour → iOS re-sampled the root grey.
// The sheet mechanics themselves are owned by qa-admin-glass; the two checks restated here are
// restated ON PURPOSE, because they are what the owner SEES at the bottom edge.
// ══════════════════════════════════════════════════════════════════════════════════════════════
console.log("\n▭▭▭ iOS chrome-tint LOCK — THE ADMIN ▭▭▭");

// ── A. One colour, and the page floor matches it ──
aHas(/html\{[^}]*background:\s*#1D1D22/i,
  "Admin root background is #1D1D22 (the colour iOS paints BOTH bar strips)");
aHas(/--bg:\s*#1D1D22/i,
  "Admin --bg matches the root exactly (page floor == chrome, no darker band above the bar)");
aHas(/html\{[^}]*color-scheme:\s*dark/i,
  "color-scheme:dark stays on the root (without it iOS paints its own light furniture)");
aHas(/body\{[^}]*background:\s*var\(--bg\)/i,
  "the page itself is painted with var(--bg) — the floor never diverges from the root");
aHas(/body\{[^}]*padding:\s*env\(safe-area-inset-top\)\s*0\s*env\(safe-area-inset-bottom\)/i,
  "both safe areas are painted by the page (the website recipe — no unpainted strip)");

// ── B. The metas: theme-color is the trap, black-translucent + viewport-fit are the recipe ──
aAbsent(/<meta[^>]+name=["']theme-color["']/i,
  "no theme-color meta on the Admin (one meta would tint both edges and fight the root colour)");
aHas(/apple-mobile-web-app-status-bar-style["']\s+content=["']black-translucent/i,
  "status bar stays black-translucent (the strips read the page, not a solid fill)");
aHas(/viewport-fit=cover/i,
  "viewport-fit=cover keeps the page under both bars (nothing to leave a pale gap)");

// ── C. The bottom edge: NOTHING filled may be parked there ──
// A position:fixed, filled element sitting on bottom:0 lives in the layer iOS never re-samples,
// so the bar froze on a dark ghost of it (owner 07-28: "it paints that bottom a darker gray when
// I slide it down, and a refresh fixes it"). The sheet is the ONLY one allowed, and only because
// it is display:none the moment it closes. A new one appearing here fails this lock.
(() => {
  const parked = [...admin.matchAll(/([^{}\n]{1,60})\{([^}]*position:\s*fixed[^}]*)\}/g)]
    .filter(([, , body]) => /bottom:\s*0/.test(body) && /background:\s*(#|rgb|var\(--(bg|sheet))/i.test(body))
    .map(([, sel]) => sel.trim().split(/\s*,\s*/).pop().trim());
  const stray = parked.filter((s) => !/^\.sheet$/.test(s));
  stray.length === 0
    ? ok(`only the sheet is parked on the bottom edge (${parked.length} filled fixed rule${parked.length === 1 ? "" : "s"}, allow-listed)`)
    : no(`a filled element is parked on the bottom edge: ${stray.join(" · ")} — iOS will ghost it into the bar. Hide it, or don't fill it.`);
})();
aHas(/_restoreSheetLayout[\s\S]{0,1600}?style\.display\s*=\s*['"]none['"]/,
  "a closed sheet is HIDDEN, not parked off-screen (this WAS the darker-bar bug, 07-28)");
aAbsent(/documentElement[\s\S]{0,80}?style\.backgroundColor\s*=/,
  "nothing re-stamps the root background-colour in-page (that re-sampling WAS the dark band)");
aAbsent(/<meta[^>]+name=["']theme-color["']|setThemeTone\s*\([^)]*\)\s*\{[^}]*content/i,
  "no code path recreates a theme-color meta on the Admin");

// ── D. The bottom stays boring while you scroll ──
aAbsent(/addEventListener\(\s*['"]scroll['"][^)]*\)[^;]{0,200}(theme-color|documentElement\.style\.background)/i,
  "no scroll handler repaints the Admin chrome (the bottom stays boring)");

console.log(`\n  tint lock PASS: ${pass}  FAIL: ${fail}\n`);
if (fail) console.error("✗ THE iOS CHROME TINT IS BROKEN. This is the bottom edge the owner reads every day, found\n" +
  "  over an all-day on-device hunt and re-broken three times since. You cannot see it in a headless\n" +
  "  browser. Restore the invariant above — do NOT edit this lock to make a change pass.\n");
process.exit(fail ? 1 : 0);
